// Picks which college profile (colleges/<id>/) the app is built for and writes
// config/college.ts, which the rest of the app imports. Runs automatically after
// `pnpm install` and before dev / build / test / kit, so you rarely call it yourself.
//
// Which college? First match wins:
//   1. the COLLEGE environment variable   (set this on Vercel)
//   2. COLLEGE=<id> in the .env file at the repo root   (pnpm setup writes it)
//   3. "example"
//
//   node scripts/use-college.mjs           pick and write
//   node scripts/use-college.mjs --print   only print the id
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

export function activeCollege() {
  if (process.env.COLLEGE) return { id: process.env.COLLEGE.trim(), from: "COLLEGE environment variable" };
  const envFile = path.join(root, ".env");
  if (fs.existsSync(envFile)) {
    const m = fs.readFileSync(envFile, "utf8").match(/^\s*COLLEGE\s*=\s*"?([\w-]+)"?\s*$/m);
    if (m) return { id: m[1], from: ".env file" };
  }
  return { id: "example", from: "default" };
}

function main() {
  const { id, from } = activeCollege();
  if (process.argv.includes("--print")) return console.log(id);

  // The live website must never quietly fall back to the placeholder college.
  if (process.env.VERCEL && from === "default") {
    console.error("\n✖ COLLEGE is not set. In Vercel → Project → Settings → Environment Variables, add COLLEGE = your college id (e.g. iedc).\n");
    process.exit(1);
  }
  const dir = path.join(root, "colleges", id);
  if (!fs.existsSync(path.join(dir, "college.ts"))) {
    const have = fs.readdirSync(path.join(root, "colleges")).filter((d) => fs.existsSync(path.join(root, "colleges", d, "college.ts")));
    console.error(`\n✖ No college profile "${id}" (from ${from}). Available: ${have.join(", ")}. Run \`pnpm setup\` to create one.\n`);
    process.exit(1);
  }
  if (!fs.existsSync(path.join(dir, "monthly.json"))) {
    fs.copyFileSync(path.join(root, "colleges", "example", "monthly.json"), path.join(dir, "monthly.json"));
  }
  const out = path.join(root, "config", "college.ts");
  const body = `// Generated by scripts/use-college.mjs. Do not edit; change the college with \`pnpm setup\` or COLLEGE=<id>.
export { college } from "../colleges/${id}/college";
export { default as monthly } from "../colleges/${id}/monthly.json";
`;
  if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== body) fs.writeFileSync(out, body);
  if (!process.argv.includes("--quiet")) console.log(`College: ${id} (${from})`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
